const { chromium } = require('playwright');
const fs = require('fs');
const root = 'http://127.0.0.1:43136/';
async function shot(page, path) { await page.screenshot({ path, fullPage: false, timeout: 5000 }); }
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const evidence = { root, viewport: '390x844 mobile', screenshots: {}, checks: {}, consoleErrors: [] };
  page.on('console', msg => { if (msg.type() === 'error') evidence.consoleErrors.push(msg.text()); });
  page.on('pageerror', err => evidence.consoleErrors.push(err.message));
  await page.goto(root + 'index_old.html', { waitUntil: 'domcontentloaded', timeout: 10000 });
  await shot(page, 'v5_before_index_trash.png');
  evidence.screenshots.before = 'v5_before_index_trash.png';
  evidence.checks.before_loaded = await page.locator('#start-btn').isVisible().catch(() => false);
  await page.goto(root, { waitUntil: 'domcontentloaded', timeout: 10000 });
  await shot(page, 'v5_after_entry.png');
  evidence.screenshots.after_entry = 'v5_after_entry.png';
  evidence.checks.after_entry_loaded = await page.locator('#start-btn').isVisible().catch(() => false);
  evidence.checks.title_text = await page.locator('#game-title-text').innerText().catch(() => 'missing');
  await page.locator('#start-btn').click({ timeout: 5000 });
  await page.waitForTimeout(1200);
  evidence.checks.canvas_count = await page.locator('canvas').count();
  evidence.checks.hud_body_armor = await page.locator('#health-display').innerText().catch(() => 'missing');
  evidence.checks.wanted_display = await page.locator('#stars-display').innerText().catch(() => 'missing');
  await shot(page, 'v5_after_spawn.png');
  evidence.screenshots.after_spawn = 'v5_after_spawn.png';
  await page.locator('#btn-switch').click({ timeout: 5000 });
  await page.locator('#btn-rotate').click({ timeout: 5000 });
  await page.locator('#btn-interact').click({ timeout: 5000 });
  await page.waitForTimeout(500);
  evidence.checks.weapon_after_switch = await page.locator('#weapon-display').innerText().catch(() => 'missing');
  await shot(page, 'v5_after_merge.png');
  evidence.screenshots.after_merge = 'v5_after_merge.png';
  evidence.checks.console_error_count = evidence.consoleErrors.length;
  fs.writeFileSync('runtime_evidence.json', JSON.stringify(evidence, null, 2));
  await browser.close();
  if (!evidence.checks.after_entry_loaded || evidence.checks.canvas_count < 1) process.exit(1);
})();
