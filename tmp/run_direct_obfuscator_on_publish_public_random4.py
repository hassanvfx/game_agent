from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
PUBLISH_REPORT_PATH = REPO_ROOT / "tmp" / "game_publish_pipeline_raw_random4_report.json"
MANIFEST_PATH = REPO_ROOT / "tmp" / "publish_public_random4_direct_obfuscator_manifest.json"
RUN_ID = "run_game_obfuscator_publish_public_random4_direct"
OBFUSCATOR_ROOT = REPO_ROOT / "tools" / "game_obfuscator"
PUBLISHED_ROOT = REPO_ROOT / "games" / "published" / "obfuscated_direct_from_public"


def main() -> None:
    report = json.loads(PUBLISH_REPORT_PATH.read_text(encoding="utf-8"))
    deploy_results = report["deployment"]["results"]

    manifest = {
        "run_label": "publish_public_random4_direct",
        "description": "Direct obfuscator replay on public deploy outputs generated by game_publish_pipeline for the 4-game baseline.",
        "games": [
            {
                "game_id": item["game_id"],
                "display_name": item["game_id"],
                "source_path": item["deploy_dir"],
                "output_path": str((PUBLISHED_ROOT / item["game_id"] / f"remix-{item['remix_uuid']}").resolve()),
            }
            for item in deploy_results
        ],
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    command = [
        sys.executable,
        str(OBFUSCATOR_ROOT / "scripts" / "game_obfuscator_cli.py"),
        "start",
        "--manifest",
        str(MANIFEST_PATH),
        "--run-id",
        RUN_ID,
        "--output-root",
        str(PUBLISHED_ROOT),
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    raise SystemExit(result.returncode)


if __name__ == "__main__":
    main()