#!/usr/bin/env python3
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = ROOT / "tools/game_refactoring/prompts/operators_v2"
WORKFLOW = ROOT / "tools/game_refactoring/scripts/game_workflow.py"
JOURNAL = ROOT / "docs/journals/creative-remix-v4-merged-prompts.md"

VISUALS_BASE = PROMPTS / "02_creative_remix_v4_visuals_base.md"
VISUAL_UI_REFINE = PROMPTS / "03_creative_remix_v4_visual_ui_refine.md"
VISUALS_UNIFIED = PROMPTS / "03_creative_remix_v4_visuals_unified.md"

UNIFIED_HEADER = """<!-- CREATIVE REMIX V4 PRODUCTION PROMPT -->
<!-- This file is new v4 material. Existing v3/v1 source prompts remain source-only and are not modified. -->
<!-- Generated by merging Remix v4 visuals_base + visual_ui_refine. -->

# Creative Remix v4 — Stage 3 — Unified Visual Transformation and UI Refinement

You are performing the single unified visual pass for Creative Remix v4.

This stage combines the responsibilities of the former v4 `visuals_base` and `visual_ui_refine` nodes. It must execute the main procedural visual transformation and refine the UI/HUD/mobile readability in the same pass, without splitting visual implementation and visual polish into separate workers.

This is not final mobile repair. Do not take over the aggressive console-fixing, monkey-tapping, or final crash-repair contract. Final runtime repair remains the job of `final_mobile_repair_aggressive`.

## Unified stage mission

In one comprehensive visual pass:

1. execute the authored world and procedural visual system from upstream v4 planning
2. implement animated, motion-graphic, level-reactive backgrounds
3. create recognizable procedural characters, items, props, icons, and motifs
4. preserve the mechanics and control model
5. refine HUD, menus, buttons, overlays, layout, and mobile readability
6. use screenshot/runtime evidence where available
7. preserve Playwright/runtime discipline
8. leave final code-level runtime cleanup to the aggressive final repair stage

## Non-negotiable invariants

- Do not break mechanics.
- Do not rewrite core gameplay logic.
- Do not alter controls, collisions, scoring, win/loss semantics, timing, or game loop behavior for visual reasons.
- Prefer CSS/SVG/Canvas/DOM procedural visuals over stock-image-led remixes.
- Keep the visual identity animated, procedural, recognizable, level-reactive, and theme-specific.
- Keep UI/HUD readable and mobile-safe.
- Use the assigned Playwright/runtime only when browser-grounded evidence is needed.
- Do not use external/system browsers or alternate localhost ports.
- Do not flatten the authored visual direction during UI cleanup.

## Combined acceptance bar

This stage passes only when the game has a strong procedural visual identity and the presentation is readable/actionable enough for the final repair stage to focus on code-level runtime, mobile, and screenshot-verified blockers.

---

# Unified Source-Derived Instruction Library

The sections below are the exact v4 source prompts merged into this unified visual pass. Follow the unified contract above first, then use these sections as detailed operating requirements where they do not conflict.
"""


def build_unified_prompt() -> None:
    base = VISUALS_BASE.read_text(encoding="utf-8")
    refine = VISUAL_UI_REFINE.read_text(encoding="utf-8")

    content = "\n\n".join(
        [
            UNIFIED_HEADER,
            "<!-- ====================================================================== -->\n"
            "<!-- SOURCE: 02_creative_remix_v4_visuals_base.md -->\n"
            "<!-- ====================================================================== -->\n",
            base,
            "\n<!-- END SOURCE: 02_creative_remix_v4_visuals_base.md -->\n",
            "<!-- ====================================================================== -->\n"
            "<!-- SOURCE: 03_creative_remix_v4_visual_ui_refine.md -->\n"
            "<!-- ====================================================================== -->\n",
            refine,
            "\n<!-- END SOURCE: 03_creative_remix_v4_visual_ui_refine.md -->\n",
        ]
    )

    VISUALS_UNIFIED.write_text(content.rstrip() + "\n", encoding="utf-8")


def update_workflow() -> None:
    text = WORKFLOW.read_text(encoding="utf-8")
    if '"id": "visuals_unified"' in text:
        return

    old = """            {
                "id": "visuals_base",
                "prompt_file": "prompts/operators_v2/02_creative_remix_v4_visuals_base.md",
                "accepted_upstream_statuses": ["ok", "warning"],
                "requires_contract": True,
            },
            {
                "id": "visual_ui_refine",
                "prompt_file": "prompts/operators_v2/03_creative_remix_v4_visual_ui_refine.md",
                "accepted_upstream_statuses": ["ok", "warning"],
                "requires_contract": True,
            },
"""
    new = """            {
                "id": "visuals_unified",
                "prompt_file": "prompts/operators_v2/03_creative_remix_v4_visuals_unified.md",
                "accepted_upstream_statuses": ["ok", "warning"],
                "requires_contract": True,
            },
"""

    if old not in text:
        raise RuntimeError("Could not find v4 visuals_base + visual_ui_refine workflow block.")
    WORKFLOW.write_text(text.replace(old, new, 1), encoding="utf-8")


def update_journal() -> None:
    marker = "### Remix v4 Unified Visual Pass"
    text = JOURNAL.read_text(encoding="utf-8")
    if marker in text:
        return

    now = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    entry = f"""

{marker}
- Recorded at: `{now}`
- Decision: merge `visuals_base` and `visual_ui_refine` into one Remix v4 visual pass.
- New node id: `visuals_unified`
- New prompt file: `tools/game_refactoring/prompts/operators_v2/03_creative_remix_v4_visuals_unified.md`
- Source prompts appended into unified prompt:
  - `02_creative_remix_v4_visuals_base.md`
  - `03_creative_remix_v4_visual_ui_refine.md`
- Updated `creative_remix_v4` stage list:
  1. `remix_inference_plus`
  2. `world_design_superprompt`
  3. `visuals_unified`
  4. `final_mobile_repair_aggressive`
- Remix 3 prompts remain untouched.
- The unified visual pass preserves both responsibilities:
  - procedural animated visual transformation
  - HUD/UI/mobile visual refinement with runtime/screenshot discipline
"""
    JOURNAL.write_text(text.rstrip() + entry, encoding="utf-8")


def validate() -> None:
    prompt = VISUALS_UNIFIED.read_text(encoding="utf-8")
    required_prompt_terms = [
        "Unified Visual Transformation and UI Refinement",
        "SOURCE: 02_creative_remix_v4_visuals_base.md",
        "SOURCE: 03_creative_remix_v4_visual_ui_refine.md",
        "Do not break mechanics.",
        "animated, procedural, recognizable, level-reactive",
        "Playwright/runtime discipline",
    ]
    missing_prompt = [term for term in required_prompt_terms if term not in prompt]
    if missing_prompt:
        raise AssertionError(f"unified prompt missing: {missing_prompt}")

    workflow = WORKFLOW.read_text(encoding="utf-8")
    if '"id": "visuals_unified"' not in workflow:
        raise AssertionError("workflow missing visuals_unified node")
    if '"id": "visuals_base"' in workflow or '"id": "visual_ui_refine"' in workflow:
        raise AssertionError("workflow still contains split v4 visual nodes")
    if "prompts/operators_v2/03_creative_remix_v4_visuals_unified.md" not in workflow:
        raise AssertionError("workflow missing unified prompt reference")

    journal = JOURNAL.read_text(encoding="utf-8")
    if "### Remix v4 Unified Visual Pass" not in journal:
        raise AssertionError("journal missing unified visual pass entry")


def main() -> None:
    build_unified_prompt()
    update_workflow()
    update_journal()
    validate()
    print("v4_visual_passes_merged_and_validated")


if __name__ == "__main__":
    main()